// Copies the web game's pure rule code (src/sim, src/ai, src/data) into the
// roblox-ts project at roblox/src/shared/game/{sim,ai,data}.
// Files under roblox/overrides/<dir>/<file>.ts replace the same-path copy.
// Writes are incremental: unchanged files are left alone (so rojo serve keeps
// working), and target files with no source any more are deleted.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const robloxRoot = resolve(here, "..");
const srcRoot = join(repoRoot, "src");
const overridesRoot = join(robloxRoot, "overrides");
const destRoot = join(robloxRoot, "src", "shared", "game");
const dirs = ["sim", "ai", "data"];

const isTs = (f) => f.endsWith(".ts") && !f.endsWith(".test.ts");
const listTs = (d) => (existsSync(d) ? readdirSync(d).filter(isTs).sort() : []);

// Desired output: file name (within a dir) -> full content.
const desired = new Map(); // key: "<dir>/<file>"
let overridden = 0;
for (const dir of dirs) {
  const srcDir = join(srcRoot, dir);
  for (const file of listTs(srcDir)) {
    let body = readFileSync(join(srcDir, file), "utf8");
    if (dir === "sim" && file === "constants-core.ts") {
      // The Roblox field is 1.5x the web field: patch the FIELD_SCALE line in the copy only.
      const webScale = "export const FIELD_SCALE = 1;";
      if (!body.includes(webScale)) {
        console.error(`sync-game: ${webScale} not found in src/${dir}/${file}; cannot patch Roblox field scale`);
        process.exit(1);
      }
      body = body.replace(webScale, "export const FIELD_SCALE = 1.5;");
    }
    const header = `// AUTO-GENERATED by scripts/sync-game.mjs from src/${dir}/${file} — do not edit here\n`;
    desired.set(`${dir}/${file}`, header + body);
  }
  const ovDir = join(overridesRoot, dir);
  for (const file of listTs(ovDir)) {
    const body = readFileSync(join(ovDir, file), "utf8");
    const header = `// AUTO-GENERATED by scripts/sync-game.mjs from roblox/overrides/${dir}/${file} — do not edit here\n`;
    desired.set(`${dir}/${file}`, header + body);
    overridden++;
  }
}

let written = 0;
let unchanged = 0;
let deleted = 0;
for (const [key, content] of desired) {
  const target = join(destRoot, key);
  mkdirSync(dirname(target), { recursive: true });
  if (existsSync(target) && readFileSync(target, "utf8") === content) {
    unchanged++;
    continue;
  }
  writeFileSync(target, content, "utf8");
  written++;
}

for (const dir of dirs) {
  const destDir = join(destRoot, dir);
  for (const file of listTs(destDir)) {
    if (!desired.has(`${dir}/${file}`)) {
      rmSync(join(destDir, file));
      deleted++;
    }
  }
}

console.log(
  `sync-game: written=${written} unchanged=${unchanged} deleted=${deleted} overridden=${overridden} (${destRoot})`,
);
