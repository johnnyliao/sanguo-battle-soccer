import { describe, expect, it } from 'vitest';
import { R0_AWAY, R0_CHECKPOINT, R0_HOME, R0_SEED, createSelfPlay } from './selfplay';

interface Checkpoint {
  tick: number;
  home: number;
  away: number;
  digest: string;
}

/** Node's fs without @types/node (the root tsconfig has none): reached through the runtime's process object. */
interface NodeFs {
  writeFileSync(path: string, data: string): void;
}
interface NodeProcess {
  cwd(): string;
  env: Record<string, string | undefined>;
  getBuiltinModule(id: 'node:fs'): NodeFs;
}
const nodeProcess = (globalThis as unknown as { process: NodeProcess }).process;

const MATCH_TIMEOUT_MS = 600_000;

function runScenario(): Checkpoint[] {
  const sp = createSelfPlay(R0_SEED, R0_HOME, R0_AWAY);
  const out: Checkpoint[] = [];
  while (!sp.done()) {
    sp.step(R0_CHECKPOINT);
    const [home, away] = sp.score();
    out.push({ tick: sp.tick, home, away, digest: sp.digest() });
  }
  return out;
}

function goldenSource(cps: Checkpoint[]): string {
  const lines = cps.map(
    (c) => `  { tick: ${c.tick}, home: ${c.home}, away: ${c.away}, digest: "${c.digest}" },`,
  );
  return [
    '// AUTO-GENERATED by src/ai/selfplay.test.ts (WRITE_GOLDEN=1) from the web build. Do not edit.',
    'export const R0_GOLDEN: { tick: number; home: number; away: number; digest: string }[] = [',
    ...lines,
    '];',
    '',
  ].join('\r\n');
}

describe('R0 self-play golden', () => {
  it(
    'is deterministic on web and collects checkpoints',
    () => {
      const first = runScenario();
      const second = runScenario();
      expect(second).toEqual(first);
      expect(first.length).toBeGreaterThan(1);

      if (nodeProcess.env.WRITE_GOLDEN === '1') {
        const target = `${nodeProcess.cwd()}/roblox/src/server/golden.ts`;
        nodeProcess.getBuiltinModule('node:fs').writeFileSync(target, goldenSource(first));
      }
    },
    MATCH_TIMEOUT_MS,
  );
});
